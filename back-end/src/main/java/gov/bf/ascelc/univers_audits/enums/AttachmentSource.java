package gov.bf.ascelc.univers_audits.enums;


public enum AttachmentSource {
    // Fournie par le déclarant lors du dépôt initial
    INITIAL_SUBMISSION,
    // Collectée sur le terrain par les contrôleurs d'État
    FIELD_INVESTIGATION,
    // Capture d'écran d'un réseau social (Facebook, WhatsApp...)
    SOCIAL_MEDIA,
    // Publication dans un média (presse, TV, radio)
    PRESS_MEDIA,
    // Document produit par un auditeur externe
    EXTERNAL_AUDIT,
    OTHER
}